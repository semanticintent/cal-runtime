// Generates src/benchmarks/data.ts from data/benchmarks/*.json (the sources of truth).
// Run: node scripts/build-benchmarks.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const ev = JSON.parse(readFileSync('data/benchmarks/event-ratios.json', 'utf8'))
const bea = JSON.parse(readFileSync('data/benchmarks/bea-output-multipliers.json', 'utf8'))
const ts = `// GENERATED by scripts/build-benchmarks.mjs from data/benchmarks/*.json. Do not edit by hand.
export const EVENT_RATIOS = ${JSON.stringify(ev, null, 1)} as const

export const BEA_OUTPUT_MULTIPLIERS = ${JSON.stringify(bea)} as const
`
writeFileSync('src/benchmarks/data.ts', ts)
console.log('src/benchmarks/data.ts written')
